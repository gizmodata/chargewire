// Generates the site's pages that come from ../spec, the single source of truth:
//
//   src/content/docs/specification.md    spec/warp-sql.md, each "§N.M" a link to its heading
//   src/content/docs/reference/endpoints.md   Appendix B with each operation's OpenAPI summary
//   src/content/docs/conformance.md      conformance/README.md, and what each test file covers
//   src/data/spec-sections.json          section number -> heading anchor, for <Spec s="6.1" />
//   public/openapi.yaml, public/openapi.json   the OpenAPI document, for Swagger UI and download
//
//   node scripts/generate.mjs                 write all of them
//   node scripts/generate.mjs --public-only   only public/ (npm run build does this first)
//   node scripts/generate.mjs --check         fail if a committed page differs from what the spec
//                                             makes, or a diagram is stale (render_diagrams --check)
import GithubSlugger from 'github-slugger';
import { load as loadYaml } from 'js-yaml';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(site, '..');
const specPath = path.join(repo, 'spec/warp-sql.md');
const openapiPath = path.join(repo, 'spec/openapi.yaml');
const HEADER = 'Generated by site/scripts/generate.mjs from {source}. Do not edit: change the source and run npm run generate.';

// ---- The specification ----

/** Section number ("6.1", "11", "A") -> the anchor Starlight gives its heading. */
function sections(spec) {
	const slugger = new GithubSlugger();
	const map = {};
	let inFence = false;
	for (const line of spec.split('\n')) {
		if (/^(```|~~~)/.test(line)) inFence = !inFence;
		if (inFence) continue;
		const heading = line.match(/^(#{2,6}) (.*)$/);
		if (!heading) continue;
		// The slug of the text as rendered: code spans keep their text, emphasis marks go.
		const text = heading[2].replace(/`([^`]*)`/g, '$1').replace(/\*\*|__/g, '');
		const slug = slugger.slug(text);
		const number = text.match(/^(\d+(?:\.\d+)*)\.? /) ?? text.match(/^Appendix ([A-Z])\./);
		if (number && !(number[1] in map)) map[number[1]] = slug;
	}
	return map;
}

/** Links every "§N.M" in prose (not in headings, code spans or code blocks) to its heading. */
function linkSections(spec, map, page = '') {
	let inFence = false;
	const missing = new Set();
	const lines = spec.split('\n').map((line) => {
		if (/^(```|~~~)/.test(line)) inFence = !inFence;
		if (inFence || /^#{1,6} /.test(line)) return line;
		return line
			.split(/(`[^`]*`)/)
			.map((part, i) =>
				i % 2 === 1
					? part
					: part.replace(/(\[[^\]]*\]\([^)]*\))|§(\d+(?:\.\d+)*)/g, (whole, link, number) => {
							if (link) return link;
							if (!(number in map)) {
								missing.add(number);
								return whole;
							}
							return `[§${number}](${page}#${map[number]})`;
						}),
			)
			.join('');
	});
	if (missing.size) throw new Error(`a reference to sections the specification doesn't have: ${[...missing].join(', ')}`);
	return lines.join('\n');
}

function specificationPage(spec, map) {
	const status = spec.match(/^\*\*Status:\*\* ([^\n]*(?:\n[^\n]+)*)/m);
	const body = linkSections(spec.replace(/^# [^\n]*\n+/, ''), map);
	const version = spec.match(/\*\*Status:\*\* (\d+\.\d+\.\d+)/)?.[1] ?? '';
	if (!status || !version) throw new Error('spec/warp-sql.md has no "**Status:** X.Y.Z" line');
	return (
		`---\ntitle: Specification\n` +
		`description: ${JSON.stringify(`The Warp SQL protocol, version 1 (specification ${version}): SQL over HTTP with Arrow IPC streams.`)}\n` +
		`editUrl: https://github.com/gizmodata/warp-sql/edit/main/spec/warp-sql.md\n` +
		`tableOfContents:\n  maxHeadingLevel: 3\n---\n\n` +
		`<!-- ${HEADER.replace('{source}', 'spec/warp-sql.md')} -->\n\n` +
		`:::note[The source]\nThis page is [\`spec/warp-sql.md\`](https://github.com/gizmodata/warp-sql/blob/main/spec/warp-sql.md), ` +
		`rendered as it is. Its endpoints are also described for tools in the [OpenAPI document](/reference/openapi/).\n:::\n\n` +
		body.trimEnd() +
		'\n'
	);
}

// ---- Endpoints (Appendix B with the OpenAPI document's summaries) ----

function endpointsPage(spec, doc, map) {
	const appendix = spec.split('## Appendix B. Endpoints')[1];
	if (!appendix) throw new Error('spec/warp-sql.md has no Appendix B');
	const rows = [...appendix.matchAll(/^\| `([A-Z]+)` \| `([^`]+)` \| §([\d.]+) \| ([^|]*)\|/gm)];
	if (rows.length < 30) throw new Error(`Appendix B: only ${rows.length} endpoints found`);
	const lines = [];
	const seen = new Set();
	for (const [, method, short, section, capability] of rows) {
		const full = short.startsWith('…') ? short.replace('…', '/warp/v1/sessions/{session_id}') : short;
		const op = doc.paths[full]?.[method.toLowerCase()];
		if (!op) throw new Error(`Appendix B lists ${method} ${full}, which spec/openapi.yaml doesn't have`);
		seen.add(`${method} ${full}`);
		const tag = op.tags?.[0] ?? 'default';
		const swagger = `/reference/openapi/#/${encodeURIComponent(tag)}/${op.operationId}`;
		const auth = op.security && op.security.length === 0 ? 'none' : 'bearer';
		const cap = capability.trim() || '';
		lines.push(
			`| \`${method}\` | [\`${full}\`](${swagger}) | ${op.summary} | [§${section}](/specification/#${map[section]}) | ${cap} | ${auth} |`,
		);
	}
	for (const [p, item] of Object.entries(doc.paths)) {
		for (const m of Object.keys(item)) {
			if (['get', 'post', 'patch', 'delete', 'put'].includes(m) && !seen.has(`${m.toUpperCase()} ${p}`)) {
				throw new Error(`spec/openapi.yaml has ${m.toUpperCase()} ${p}, which Appendix B doesn't list`);
			}
		}
	}
	return (
		`---\ntitle: Endpoints\ndescription: Every endpoint of Warp SQL version 1, with its section of the specification and its OpenAPI operation.\n` +
		`editUrl: false\n---\n\n<!-- ${HEADER.replace('{source}', 'spec/warp-sql.md (Appendix B) and spec/openapi.yaml')} -->\n\n` +
		`Every endpoint of version 1, from the specification's [Appendix B](/specification/#${map['B']}), with the summary its ` +
		`OpenAPI operation gives. The path opens the operation in the [OpenAPI reference](/reference/openapi/); the section is ` +
		`where the specification defines it. *Auth* \`none\` means the endpoint takes no token; every other endpoint needs ` +
		`\`Authorization: Bearer <token>\` (§4.2). A capability means the endpoint is optional: a client uses it only when ` +
		`discovery (\`GET /warp\`) lists that capability.\n\n` +
		`| Method | Path | What | Spec | Capability | Auth |\n|---|---|---|---|---|---|\n` +
		lines.join('\n') +
		'\n'
	).replace('(§4.2)', `([§4.2](/specification/#${map['4.2']}))`);
}

// ---- Conformance (conformance/README.md, and each test file's docstring) ----

const GITHUB = 'https://github.com/gizmodata/warp-sql';

function conformancePage(map) {
	const dir = path.join(repo, 'conformance');
	const readme = fs.readFileSync(path.join(dir, 'README.md'), 'utf8');
	const tests = fs
		.readdirSync(path.join(dir, 'tests'))
		.filter((f) => /^test_.*\.py$/.test(f))
		.sort();
	const rows = tests.map((file) => {
		const source = fs.readFileSync(path.join(dir, 'tests', file), 'utf8');
		const doc = source.match(/^"""([\s\S]*?)(?:\n\n|""")/);
		if (!doc) throw new Error(`conformance/tests/${file} has no docstring saying what it covers`);
		const covers = doc[1].replace(/\s+/g, ' ').trim().replace(/^Spec /, '');
		const count = (source.match(/^(?:async )?def test_/gm) ?? []).length;
		return `| [\`${file}\`](${GITHUB}/blob/main/conformance/tests/${file}) | ${count} | ${covers} |`;
	});
	const total = tests.reduce(
		(sum, file) => sum + (fs.readFileSync(path.join(dir, 'tests', file), 'utf8').match(/^(?:async )?def test_/gm) ?? []).length,
		0,
	);
	// The README's links are relative to conformance/: point them at the repository.
	const body = readme
		.replace(/^# [^\n]*\n+/, '')
		.replace(/\]\((?!https?:|#)([^)]+)\)/g, (_, target) => {
			const resolved = path.posix.normalize(path.posix.join('conformance', target));
			const kind = fs.existsSync(path.join(repo, resolved)) && fs.statSync(path.join(repo, resolved)).isDirectory() ? 'tree' : 'blob';
			return `](${GITHUB}/${kind}/main/${resolved})`;
		});
	const coverage =
		`## What each file covers\n\n` +
		`${total} test functions (some run several cases), in the suite's [\`tests/\`](${GITHUB}/tree/main/conformance/tests):\n\n` +
		`| File | Tests | Covers |\n|---|---|---|\n` +
		rows.join('\n') +
		'\n\n';
	const anchor = '## Every response against the OpenAPI document';
	const page = body.includes(anchor) ? body.replace(anchor, coverage + anchor) : body.trimEnd() + '\n\n' + coverage;
	return (
		`---\ntitle: Conformance\ndescription: "Warp SQL's black-box conformance suite: how to run it against a server, what each test file covers, and the MUSTs it does not test yet."\n` +
		`editUrl: ${GITHUB}/edit/main/conformance/README.md\n---\n\n` +
		`<!-- ${HEADER.replace('{source}', 'conformance/README.md and conformance/tests/test_*.py')} -->\n\n` +
		linkSections(page, map, '/specification/').trimEnd() +
		'\n'
	);
}

// ---- Output ----

function outputs({ publicOnly }) {
	const spec = fs.readFileSync(specPath, 'utf8');
	const openapiText = fs.readFileSync(openapiPath, 'utf8');
	const doc = loadYaml(openapiText);
	const files = {
		'public/openapi.yaml': openapiText,
		'public/openapi.json': JSON.stringify(doc, null, 2) + '\n',
	};
	if (publicOnly) return files;
	const map = sections(spec);
	files['src/data/spec-sections.json'] = JSON.stringify(map, null, 2) + '\n';
	files['src/content/docs/specification.md'] = specificationPage(spec, map);
	files['src/content/docs/reference/endpoints.md'] = endpointsPage(spec, doc, map);
	files['src/content/docs/conformance.md'] = conformancePage(map);
	return files;
}

const args = new Set(process.argv.slice(2));
if (args.has('--check')) {
	const drift = [];
	for (const [rel, text] of Object.entries(outputs({ publicOnly: false }))) {
		if (rel.startsWith('public/')) continue; // made at build time, not committed
		const file = path.join(site, rel);
		if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) drift.push(rel);
	}
	for (const rel of drift) console.log(`stale: site/${rel}`);
	let diagrams = 0;
	try {
		execFileSync(process.execPath, [path.join(site, 'scripts/render_diagrams.mjs'), '--check'], { stdio: 'inherit' });
	} catch {
		diagrams = 1;
	}
	if (drift.length) console.log('The generated pages differ from ../spec: run npm run generate and commit the result.');
	if (drift.length || diagrams) process.exit(1);
	console.log('generated pages match ../spec');
} else {
	const files = outputs({ publicOnly: args.has('--public-only') });
	for (const [rel, text] of Object.entries(files)) {
		const file = path.join(site, rel);
		fs.mkdirSync(path.dirname(file), { recursive: true });
		fs.writeFileSync(file, text);
		if (!args.has('--public-only')) console.log(`wrote site/${rel}`);
	}
}
